-- PostgreSQL 17. Backup and stop backend before applying. No clinical rows are deleted.
BEGIN;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS symptoms text;
ALTER TABLE public.medicines ADD COLUMN IF NOT EXISTS description text;
ALTER TABLE public.vaccinations ADD COLUMN IF NOT EXISTS notes text;
CREATE TABLE IF NOT EXISTS public.vaccine_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamp(6) NOT NULL,updated_at timestamp(6) NOT NULL,
 name varchar(120) NOT NULL,manufacturer varchar(200),description text,active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.revoked_tokens (token_hash varchar(64) PRIMARY KEY,expires_at timestamp with time zone NOT NULL);
CREATE INDEX IF NOT EXISTS idx_revoked_token_expiry ON public.revoked_tokens(expires_at);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS vet_id bigint;
ALTER TABLE public.vaccinations ADD COLUMN IF NOT EXISTS vaccine_id bigint;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.users'::regclass AND conname='fk_users_vet') THEN
  ALTER TABLE public.users ADD CONSTRAINT fk_users_vet FOREIGN KEY(vet_id) REFERENCES public.vets(id);
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.vaccinations'::regclass AND conname='fk_vaccinations_vaccine') THEN
  ALTER TABLE public.vaccinations ADD CONSTRAINT fk_vaccinations_vaccine FOREIGN KEY(vaccine_id) REFERENCES public.vaccine_types(id);
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_vet ON public.users(vet_id);
INSERT INTO public.vaccine_types(created_at,updated_at,name,active)
 SELECT CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,legacy.name,true
 FROM (SELECT min(trim(vaccine_type)) AS name FROM public.vaccinations WHERE vaccine_type IS NOT NULL AND trim(vaccine_type)<>'' GROUP BY lower(trim(vaccine_type))) legacy
 WHERE NOT EXISTS(SELECT 1 FROM public.vaccine_types v WHERE lower(trim(v.name))=lower(legacy.name));
UPDATE public.vaccinations old SET vaccine_id=(SELECT min(v.id) FROM public.vaccine_types v WHERE lower(trim(v.name))=lower(trim(old.vaccine_type)))
 WHERE old.vaccine_id IS NULL;
-- Existing User/Vet pairs are not guessed from names. ADMIN explicitly links them in the UI.
COMMIT;
