BEGIN;
ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS status varchar(20) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS revision bigint NOT NULL DEFAULT 0;
ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS cancelled_at timestamp(6);
ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS cancel_reason varchar(1000);
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='prescriptions'::regclass AND conname='prescriptions_status_check') THEN
 ALTER TABLE prescriptions ADD CONSTRAINT prescriptions_status_check CHECK(status IN ('ACTIVE','CANCELLED'));
 END IF;
END $$;
CREATE TABLE IF NOT EXISTS audit_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 occurred_at timestamptz(6) NOT NULL,
 actor varchar(255) NOT NULL, action varchar(100) NOT NULL,
 entity_type varchar(50) NOT NULL,entity_id bigint NOT NULL,
 reason varchar(1000),before_state text,after_state text
);
CREATE INDEX IF NOT EXISTS idx_audit_occurred ON audit_events(occurred_at);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_events(entity_type,entity_id);
COMMIT;
