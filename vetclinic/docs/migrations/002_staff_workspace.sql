-- PostgreSQL 17. Apply once while the backend is stopped, after backup.
-- Does not remove patient/account rows. Hibernate update alone may not widen enum checks.
BEGIN;
DO $$
DECLARE constraint_name text;
BEGIN
  FOR constraint_name IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'public.users'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) ~ '\mrole\M'
  LOOP
    EXECUTE format('ALTER TABLE public.users DROP CONSTRAINT %I', constraint_name);
  END LOOP;
END $$;
ALTER TABLE public.users ADD CONSTRAINT users_role_check CHECK (role IN ('ADMIN','VET','RECEPTIONIST'));
CREATE TABLE IF NOT EXISTS public.support_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL,
 requested_by varchar(255) NOT NULL, subject varchar(200) NOT NULL,
 description text NOT NULL, status varchar(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.knowledge_documents (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL,
 title varchar(200) NOT NULL, content text NOT NULL, source varchar(1000)
);
CREATE INDEX IF NOT EXISTS idx_visits_vet_schedule ON public.visits(vet_id, scheduled_at);
CREATE INDEX IF NOT EXISTS idx_support_requester ON public.support_requests(requested_by);
CREATE INDEX IF NOT EXISTS idx_vaccinations_due ON public.vaccinations(next_due_date);
COMMIT;
